const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const test = require('node:test');
const {
  autogeneratedSidebar,
  parseSidebarSource,
  serializeSidebarModule,
} = require('./parse-sidebar');

const fixtures = [
  ['identity-service.js', 7],
  ['storage-service.js', 8],
  ['hosting-service.js', 8],
  ['email-service.js', 8],
];

for (const [name, count] of fixtures) {
  test(`parses ${name} as data and serializes without code`, () => {
    const source = fs.readFileSync(path.join(__dirname, 'fixtures', name), 'utf8');
    const data = parseSidebarSource(source);
    assert.ok(data);
    const items = data[Object.keys(data)[0]];
    assert.ok(Array.isArray(items));
    assert.equal(items.length, count);
    assert.deepEqual(items[0], {type: 'doc', id: 'index', label: 'Overview'});
    const serialized = serializeSidebarModule(data);
    assert.match(serialized, /^module\.exports = \{/);
    assert.doesNotMatch(serialized, /=>|\brequire\s*\(|\beval\s*\(|\bFunction\s*\(/);
  });
}

test('parses a JSON sidebar', () => {
  const data = parseSidebarSource(
    '{"tutorialSidebar":[{"type":"doc","id":"index","label":"Overview"}]}',
  );
  assert.deepEqual(data, {
    tutorialSidebar: [{type: 'doc', id: 'index', label: 'Overview'}],
  });
});

test('rejects a sidebar that calls require', () => {
  const source = [
    "const sidebars = require('./sidebars.json');",
    'module.exports = sidebars;',
    '',
  ].join('\n');
  assert.equal(parseSidebarSource(source), null);
  assert.deepEqual(autogeneratedSidebar(), {
    tutorialSidebar: [{type: 'autogenerated', dirName: '.'}],
  });
});
